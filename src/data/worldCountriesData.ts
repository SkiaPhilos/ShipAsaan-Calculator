/**
 * Normalizes user input query and looks up country by:
 * - Alpha-2 code (e.g. "US", "GB", "AE", "PK")
 * - Alpha-3 code (e.g. "USA", "GBR", "ARE", "PAK")
 * - ISO Numeric code (e.g. "840", "826", "784", "586", "36")
 * - Exact Country Name
 * - Aliases list
 * - Case-insensitive partial matching
 */
export function lookupWorldCountry(
  query: string,
  customList?: InternationalCountryZone[]
): InternationalCountryZone | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  const list = customList && customList.length > 0 ? customList : worldCountriesList;

  // 1. Direct Alpha-2 match
  const alpha2Match = list.find((c) => c.countryCode.toLowerCase() === q);
  if (alpha2Match) return alpha2Match;

  // 2. Direct Alpha-3 match
  const alpha3Match = list.find((c) => c.alpha3 && c.alpha3.toLowerCase() === q);
  if (alpha3Match) return alpha3Match;

  // 3. Numeric ISO match (exact or without leading zero, e.g. "036" vs "36")
  const numTrim = q.replace(/^0+/, "");
  const numericMatch = list.find((c) => {
    if (!c.numericCode) return false;
    const cNumTrim = c.numericCode.replace(/^0+/, "");
    return c.numericCode.toLowerCase() === q || (numTrim && cNumTrim === numTrim);
  });
  if (numericMatch) return numericMatch;

  // 4. Exact Country Name match
  const exactNameMatch = list.find((c) => c.countryName.toLowerCase() === q);
  if (exactNameMatch) return exactNameMatch;

  // 5. Aliases match
  const aliasMatch = list.find((c) =>
    c.aliases?.some((a) => a.toLowerCase() === q)
  );
  if (aliasMatch) return aliasMatch;

  // 6. Substring / partial match
  const partialMatch = list.find(
    (c) =>
      c.countryName.toLowerCase().includes(q) ||
      q.includes(c.countryName.toLowerCase()) ||
      c.aliases?.some((a) => a.toLowerCase().includes(q) || q.includes(a.toLowerCase()))
  );
  if (partialMatch) return partialMatch;

  return undefined;
}

/**
 * Formats a country for display with all standard ISO codes
 */
export function formatCountryDisplayName(c: InternationalCountryZone): string {
  return `${c.countryName} (${c.countryCode} / ${c.alpha3} • ${c.numericCode})`;
}
